export interface ParsedCanvas {
  nodes: BuilderNode[];
  edges: BuilderEdge[];
}


function findRegistryEntry(category: string, providerKey: string, adapterPackage: string): typeof ADAPTER_REGISTRY[number] | undefined {
  return ADAPTER_REGISTRY.find(
    (a) => a.category === category && a.providerKey === providerKey
  );
}

function gridPosition(index: number, category: string): { x: number; y: number } {
  const categoryOrder = ['platform', 'llm', 'embedder', 'store', 'blob', 'queue'];
  const col = categoryOrder.indexOf(category);
  const row = index;
  return { x: col * 280 + 40, y: row * 160 + 40 };
}

export function parseConfig(yamlString: string): ParsedCanvas {
  const parsed = yaml.load(yamlString) as Record<string, any> | null;
  if (!parsed || !parsed.docket) {
    return { nodes: [], edges: [] };
  }

  const docket = parsed.docket;
  const nodes: BuilderNode[] = [];
  const edges: BuilderEdge[] = [];

  // Add a default platform node; config does not encode platform mode.
  nodes.push({
    id: 'platform-unified',
    adapterId: 'unified',
    config: {
      port: docket.server?.port ?? 3000,
      host: docket.server?.host ?? '127.0.0.1'
    },
    position: gridPosition(0, 'platform')
  });

  const categories = ['llm', 'embedder', 'store', 'blob', 'queue'] as const;
  for (const category of categories) {
    const categoryConfig = docket.adapters?.[category];
    if (!categoryConfig || !categoryConfig.providers) continue;

    let index = 0;
    for (const [providerKey, provider] of Object.entries(categoryConfig.providers as Record<string, any>)) {
      const entry = findRegistryEntry(category, providerKey, provider.adapter);
      if (!entry) continue;

      const config: Record<string, unknown> = { ...(provider.config || {}) };
      // Normalize placeholder strings back to empty values for the inspector.
      for (const field of entry.configSchema) {
        const value = config[field.key];
        if (typeof value === 'string' && value.startsWith('<') && value.endsWith('>')) {
          config[field.key] = '';
        }
      }

      const nodeId = `${category}-${providerKey}-${index}`;
      nodes.push({
        id: nodeId,
        adapterId: entry.id,
        config,
        position: gridPosition(index, category)
      });

      edges.push({
        id: `edge-platform-${nodeId}`,
        source: 'platform-unified',
        target: nodeId,
        sourcePort: `to-${category}`,
        targetPort: 'from-platform'
      });

      index++;
    }
  }

  return { nodes, edges };
}

export function downloadFile(filename: string, content: string, type = 'text/plain'): void {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function copyToClipboard(text: string): Promise<void> {
  return navigator.clipboard.writeText(text);
}
